"""The Neuro Atlas files committed in site/static/atlas/ (written by ``syn atlas build``).

They are generated by hand, so these checks catch a hand edit or a partial build: every folder
carries its licence, the human layers never share a voxel, the pairs hold no geometry and each
brain's initial load stays within the budget of ADR D3. No network.
"""

import json
from pathlib import Path

import pytest

np = pytest.importorskip("numpy")
nib = pytest.importorskip("nibabel")

ATLAS = Path(__file__).parents[1] / "site" / "static" / "atlas"
HUMAN = ("julich", "cerebra", "cit168", "icbm_wm")
LABELLED = ("waxholm", *HUMAN)


def load(name: str) -> dict:
    return json.loads((ATLAS / name).read_text("utf-8"))


@pytest.mark.parametrize("folder", [*LABELLED, "bigbrain", "nissl"])
def test_every_folder_has_its_licence(folder):
    lic = load(f"{folder}/licence.json")
    assert lic["licence"] and lic["licence_url"] and lic["citation"] and lic["derived"]


@pytest.mark.parametrize("folder", LABELLED)
def test_rows_match_the_volume(folder):
    rows = load(f"{folder}/labels.json")["rows"]
    assert [r["index"] for r in rows] == list(range(len(rows)))
    vol = np.asarray(nib.load(ATLAS / folder / "labels.nii.gz").dataobj)
    assert int(vol.max()) == len(rows) - 1  # every value has a row, every row is drawn
    assert all(r["side"] in ("L", "R") and r["color_calm"] for r in rows[1:])


def test_human_layers_never_share_a_voxel():
    taken = None
    for layer in HUMAN:
        vol = np.asarray(nib.load(ATLAS / layer / "labels.nii.gz").dataobj) > 0
        if taken is not None:
            assert not np.any(taken & vol), f"{layer} overlaps an earlier layer"
            taken |= vol
        else:
            taken = vol


def test_pairs_have_no_geometry_and_no_grade_yet():
    pairs = load("pairs.json")
    text = json.dumps(pairs)
    assert "centroid" not in text and "voxels" not in text
    assert pairs["pairs"] and all(p["grade"] is None for p in pairs["pairs"])


def test_initial_load_within_budget():
    manifest = load("manifest.json")
    assert set(manifest["initial_load"]) == {"rat", "human"}
    assert all(b["within_budget"] for b in manifest["initial_load"].values())
